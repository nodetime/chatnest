type Route = (typeof platformRoutes)[number];
export type PlatformRouteOwner = Route["owner"];
export function platformRoute<I extends Route["id"]>(
  id: I
): Extract<Route, { id: I }> {
  const route = platformRoutes.find((item) => item.id === id);
  if (!route) {
    throw new Error("CONTRACT_ROUTE_UNKNOWN_ID");
  }
  return route as Extract<Route, { id: I }>;
}
export type PlatformHandlerName<O extends PlatformRouteOwner> = Extract<
  Route,
  { owner: O }
>["handler"];
export function bindPlatformHandlers<O extends PlatformRouteOwner, H>(
  owner: O,
  handlers: Record<PlatformHandlerName<O>, H>
) {
  const routes = platformRoutes.filter((route) => route.owner === owner);
  if (!routes.length) {
    throw new Error("CONTRACT_ROUTE_UNKNOWN_OWNER");
  }
  const expected = routes
    .map((route) => route.handler)
    .sort((a, b) => a.localeCompare(b));
  const actual = Object.keys(handlers).sort((a, b) => a.localeCompare(b));
  if (
    JSON.stringify(expected) !== JSON.stringify(actual) ||
    actual.some(
      (key) => typeof handlers[key as PlatformHandlerName<O>] !== "function"
    )
  ) {
    throw new Error("CONTRACT_ROUTE_HANDLER_COVERAGE");
  }
  return routes.map((route) => ({
    handler: handlers[route.handler as PlatformHandlerName<O>],
    method: route.method,
    path: route.path,
  }));
}
